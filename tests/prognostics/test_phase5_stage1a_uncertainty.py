# TEST 8: SIGNED IGSS SEMANTICS REMAIN UNCHANGED
# ==============================================================================

def test_signed_igss_semantics_unchanged():
    """Negative gate leakage values must be handled seamlessly without abs() or clipping."""
    X = np.array([[-1.5, -1.6], [-2.0, -2.1], [-1.8, -1.9], [-0.5, -0.6], [-0.8, -0.9], [-1.0, -1.1]])
    y = np.array([-1.8, -2.4, -2.1, -0.8, -1.1, -1.3])
    lots = np.array(["LOT_A", "LOT_A", "LOT_A", "LOT_B", "LOT_B", "LOT_B"])

    m = RidgeRegressionPrognosticModel("IGSS", "nA")
    m.fit(X, y, sample_lot_ids=lots)

    inp = PrognosticInput(
        component_id="C_NEG",
        lot_id="LOT_TEST",
        parameter_name="IGSS",
        unit="nA",
        as_of_hours=24,
        target_hours=168,
        historical_observations=[(0, -1.5), (24, -1.6)],
        data_sufficiency_passed=True,
    )
    forecast = m.predict_single(inp)

    assert forecast.is_valid
    assert forecast.predicted_value < 0.0, "Predicted IGSS must remain negative"
    assert forecast.interval_lower < forecast.predicted_value < forecast.interval_upper


# ==============================================================================
# TEST 9: MODEL COEFFICIENTS UNCHANGED BY UNCERTAINTY REFACTORING
# ==============================================================================

def test_prediction_model_coefficients_unchanged_by_uncertainty_refactoring(multi_lot_training_population):
    """The point prediction coefficients beta_0, beta_1, beta_2 must remain identical."""
    d = multi_lot_training_population

    # Fit with nested LOLO OOF uncertainty
    m_oof = RidgeRegressionPrognosticModel("IDSS", "uA", l2_reg=1.0)
    m_oof.fit(d["X"], d["y"], sample_lot_ids=d["sample_lots"])

    # Compute exact closed form beta directly from all training data
    U_arr = np.array([(transform_parameter("IDSS", d["X"][i, 0]),
                       transform_parameter("IDSS", d["X"][i, 1]))
                      for i in range(len(d["y"]))])
    u_target = np.array([transform_parameter("IDSS", v) for v in d["y"]])
    X_aug = np.column_stack([np.ones(len(U_arr)), U_arr])
    Gamma = np.diag([0.0, 1.0, 1.0])
    expected_beta = np.linalg.solve(X_aug.T @ X_aug + Gamma, X_aug.T @ u_target)

    # Must match to machine precision
    assert np.allclose(m_oof.coefficients_, expected_beta, atol=1e-12)


