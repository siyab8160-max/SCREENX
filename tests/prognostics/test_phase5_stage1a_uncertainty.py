# TEST 3: INTERNAL PREPROCESSING FIT ONLY ON INTERNAL TRAINING DATA
# ==============================================================================

def test_internal_preprocessing_fit_only_on_internal_training_data(multi_lot_training_population):
    """Internal models for each fold derive statistics strictly from their training subset."""
    d = multi_lot_training_population
    model = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    model.fit(d["X"], d["y"], sample_lot_ids=d["sample_lots"])

    # For any internal fold, training without LOT_001 cannot be affected by LOT_001
    mask_2_and_3 = (d["sample_lots"] != "LOT_CAL_001")
    m_sub = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    m_sub.fit(d["X"][mask_2_and_3], d["y"][mask_2_and_3])

    # Preprocessor parameters for m_sub depend strictly on LOT_002 and LOT_003
    expected_u0_mean = float(np.mean(d["X"][mask_2_and_3][:, 0]))
    assert math.isclose(m_sub.preprocessor_params_["u0_mean"], expected_u0_mean, rel_tol=1e-9)


# ==============================================================================
# TEST 4: CHANGING OUTER HELD-OUT TARGET CANNOT CHANGE SIGMA_EFF
# ==============================================================================

def test_changing_outer_held_out_target_cannot_change_sigma_eff(multi_lot_training_population):
    """Mutating the outer held-out lot target must produce bit-for-bit identical sigma_eff."""
    d = multi_lot_training_population
    outer_held_out = "LOT_CAL_001"
    outer_train_mask = (d["sample_lots"] != outer_held_out)

    X_train = d["X"][outer_train_mask]
    y_train = d["y"][outer_train_mask]
    sample_lots_train = d["sample_lots"][outer_train_mask]

    m1 = RidgeRegressionPrognosticModel("RDS(on)", "mOhm", l2_reg=1.0)
    m1.fit(X_train, y_train, sample_lot_ids=sample_lots_train)
    sigma_eff_clean = m1._sigma_eff_u_scalar

    # Adversarially corrupt held-out targets in external dataframe or array
    y_corrupted = d["y"].copy()
    y_corrupted[d["sample_lots"] == outer_held_out] = 999999.0

    # Fit model on outer training fold
    m2 = RidgeRegressionPrognosticModel("RDS(on)", "mOhm", l2_reg=1.0)
    m2.fit(X_train, y_train, sample_lot_ids=sample_lots_train)
    sigma_eff_corrupted = m2._sigma_eff_u_scalar

    assert sigma_eff_clean == sigma_eff_corrupted


