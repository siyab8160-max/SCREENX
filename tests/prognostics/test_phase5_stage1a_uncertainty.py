# ==============================================================================
# TEST 6: CHANGING VALIDATION/FINAL PARTITIONS CANNOT CHANGE SIGMA_EFF
# ==============================================================================

def test_changing_validation_or_final_partitions_cannot_change_sigma_eff():
    """Dummy or corrupted validation/final rows must have zero influence on training sigma_eff."""
    # Create observations with calibration lots and quarantined validation lot
    rows = []
    for lot in ["LOT_CAL_001", "LOT_CAL_002", "LOT_VAL_001"]:
        val_multiplier = 1000.0 if lot.startswith("LOT_VAL_") else 1.0
        for c in range(5):
            cid = f"{lot}_C{c+1:03d}"
            for t, v in [(0, 1.0 * val_multiplier), (24, 1.1 * val_multiplier), (168, 1.3 * val_multiplier)]:
                rows.append({
                    "lot_id": lot,
                    "component_id": cid,
                    "parameter_name": "IDSS",
                    "elapsed_hours": t,
                    "value": v,
                })
    df = pd.DataFrame(rows)

    # Strictly filter calibration partition
    df_cal = df[df["lot_id"].str.startswith("LOT_CAL_")].copy()
    piv = df_cal.pivot(index=["lot_id", "component_id"], columns="elapsed_hours", values="value").reset_index()

    X = piv[[0, 24]].values
    y = piv[168].values
    lots = piv["lot_id"].values

    m = RidgeRegressionPrognosticModel("IDSS", "uA")
    m.fit(X, y, sample_lot_ids=lots)

    assert "LOT_VAL_001" not in m.training_lot_ids
    assert m._sigma_eff_u_scalar < 1.0  # Must reflect normal noise, not the 1000x corrupted VAL lot


