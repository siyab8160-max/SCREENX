@pytest.fixture
def multi_lot_training_population() -> dict:
    """Provide a 3-lot synthetic training dataset with known lot labels."""
    rng = np.random.RandomState(42)
    lots = ["LOT_CAL_001", "LOT_CAL_002", "LOT_CAL_003"]
    n_per_lot = 15
    v0_list, v24_list, v168_list, lot_list = [], [], [], []

    for lot in lots:
        base = 1.0 if lot != "LOT_CAL_003" else 1.2
        for _ in range(n_per_lot):
            v0 = base + rng.normal(0, 0.05)
            v24 = v0 + 0.1 + rng.normal(0, 0.02)
            v168 = v0 + 0.3 + rng.normal(0, 0.04)
            v0_list.append(v0)
            v24_list.append(v24)
            v168_list.append(v168)
            lot_list.append(lot)

    X = np.column_stack([v0_list, v24_list])
    y = np.array(v168_list)
    sample_lots = np.array(lot_list)

    return {
        "X": X,
        "y": y,
        "sample_lots": sample_lots,
        "lots": lots,
    }


# ==============================================================================
# TEST 1: EVERY OOF PREDICTION GENERATED WITHOUT THE PREDICTED OBSERVATION
# ==============================================================================

def test_oof_prediction_not_trained_on_predicted_observation(multi_lot_training_population):
    """Every OOF prediction must be produced by a model fitted without the predicted lot."""
    d = multi_lot_training_population
    model = RidgeRegressionPrognosticModel("IDSS", "uA", l2_reg=1.0)
    model.fit(d["X"], d["y"], sample_lot_ids=d["sample_lots"])

    # Verify that each internal lot OOF prediction matches an independently fitted model
    # trained on the other 2 lots
    for held_lot in d["lots"]:
        mask_train = (d["sample_lots"] != held_lot)
        mask_val = (d["sample_lots"] == held_lot)

        independent_model = RidgeRegressionPrognosticModel("IDSS", "uA", l2_reg=1.0)
        independent_model.fit(d["X"][mask_train], d["y"][mask_train])

        pred_independent = independent_model.predict_transformed(d["X"][mask_val])
        u_val = np.array([transform_parameter("IDSS", v) for v in d["y"][mask_val]])
        expected_residuals = u_val - pred_independent

        # The internal model coefficients must match independent_model coefficients exactly
        X_aug_val = np.column_stack([np.ones(np.sum(mask_val)), np.array([
            (transform_parameter("IDSS", d["X"][mask_val][i, 0]),
             transform_parameter("IDSS", d["X"][mask_val][i, 1]))
            for i in range(np.sum(mask_val))
        ])])
        u_pred = X_aug_val @ independent_model.coefficients_
        assert np.allclose(expected_residuals, u_val - u_pred, atol=1e-12)


# ==============================================================================
# TEST 2: NO OUTER HELD-OUT LOT ENTERS OOF RESIDUAL CALIBRATION
# ==============================================================================

def test_no_outer_held_out_lot_enters_oof_residual_calibration(multi_lot_training_population):
    """The outer held-out lot must be 100% excluded from OOF residual generation."""
    d = multi_lot_training_population
    outer_held_out = "LOT_CAL_001"
    outer_train_mask = (d["sample_lots"] != outer_held_out)

    X_train = d["X"][outer_train_mask]
    y_train = d["y"][outer_train_mask]
    sample_lots_train = d["sample_lots"][outer_train_mask]

    model = RidgeRegressionPrognosticModel("IDSS", "uA", l2_reg=1.0)
    model.fit(X_train, y_train, sample_lot_ids=sample_lots_train)

    lineage = model.get_lineage()
    assert outer_held_out not in lineage["training_lot_ids"]
    assert model.oof_residual_count_ == len(y_train)  # Exactly 30 samples from LOT_002 and LOT_003
    assert outer_held_out not in list(np.unique(sample_lots_train))


