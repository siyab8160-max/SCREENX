# ==============================================================================
# TEST 11: INNER VALIDATION FEATURE MUTATION ADVERSARIAL ISOLATION
# ==============================================================================

def test_inner_validation_feature_mutation_adversarial_isolation(multi_lot_training_population):
    """Mutating inner validation features must not alter inner training model or statistics."""
    d = multi_lot_training_population
    lots = d["sample_lots"]
    inner_val_lot = "LOT_CAL_002"
    inner_train_mask = (lots != inner_val_lot)
    inner_val_mask = (lots == inner_val_lot)

    # 1. Fit clean inner model
    m_clean = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    m_clean.fit(d["X"][inner_train_mask], d["y"][inner_train_mask])
    beta_clean = m_clean.coefficients_.copy()
    prep_clean = dict(m_clean.preprocessor_params_)

    # 2. Mutate inner validation lot features by a huge amount
    X_mut = d["X"].copy()
    X_mut[inner_val_mask, 0] += 50.0

    # 3. Fit inner model with mutated validation features in memory
    m_mut = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    m_mut.fit(X_mut[inner_train_mask], d["y"][inner_train_mask])
    beta_mut = m_mut.coefficients_.copy()
    prep_mut = dict(m_mut.preprocessor_params_)

    # Assert inner coefficients and statistics are completely unaffected
    assert np.allclose(beta_clean, beta_mut, atol=1e-12)
    assert prep_clean == prep_mut

    # Assert prediction changes strictly via linear projection of mutated feature
    pred_clean = m_clean.predict_transformed(d["X"][inner_val_mask])
    pred_mut = m_mut.predict_transformed(X_mut[inner_val_mask])
    delta_pred = pred_mut - pred_clean
    expected_delta = beta_clean[1] * 50.0
    assert np.allclose(delta_pred, expected_delta, atol=1e-12)

    # 4. Outer sigma_eff invariance under outer held-out mutation
    outer_held_out = "LOT_CAL_001"
    outer_train_mask = (lots != outer_held_out)
    m_outer1 = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    m_outer1.fit(d["X"][outer_train_mask], d["y"][outer_train_mask], sample_lot_ids=lots[outer_train_mask])
    sigma1 = m_outer1._sigma_eff_u_scalar

    X_outer_mut = d["X"].copy()
    X_outer_mut[lots == outer_held_out, :] += 9999.0
    m_outer2 = RidgeRegressionPrognosticModel("VGS(th)", "V", l2_reg=1.0)
    m_outer2.fit(X_outer_mut[outer_train_mask], d["y"][outer_train_mask], sample_lot_ids=lots[outer_train_mask])
    sigma2 = m_outer2._sigma_eff_u_scalar

    assert sigma1 == sigma2

